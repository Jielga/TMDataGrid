// House style, enforced rather than remembered. Run by the pre-commit hook and
// by CI; `node scripts/check-house-style.mjs` on its own reports every hit.
//
// A script rather than a Vitest test because CSS Modules ignore `?raw` (Vite
// hands back the class-name map), and the stylesheets carry prose too.
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(import.meta.url), "../..");

const SKIP_DIRS = new Set([
  ".git",
  ".playwright-mcp",
  "coverage",
  "dist",
  "dist-demo",
  "node_modules",
  "playwright-report",
  "test-results",
]);

/** Generated by `version-packages`, and the repo owner's own instructions. */
const SKIP_FILES = new Set(["CHANGELOG.md", "CLAUDE.md"]);

const SCANNED = /\.(md|ts|tsx|css|mjs|js|json|ya?ml|html)$/;

function sourceFiles(dir = ROOT, found = []) {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      if (!SKIP_DIRS.has(entry)) sourceFiles(path, found);
    } else if (SCANNED.test(entry) && !SKIP_FILES.has(entry)) {
      found.push(path);
    }
  }
  return found;
}

/**
 * The em dash is out project-wide. It is non-ASCII, so it survives a trip
 * through a terminal, a commit message or a mismatched codepage only by luck,
 * and prose dense with them reads as machine-written whether or not it was. A
 * plain dash, a colon or a full stop says the same thing.
 *
 * Escaped so this file does not fail itself.
 */
const EM_DASH = "\u2014";

/**
 * `headingSlug` strips `:` and `?` from a heading but keeps `-`, so a spaced
 * dash lands in the slug as three hyphens and every hand-written link to that
 * heading breaks. Swapping an em dash for a plain one did exactly that once.
 */
const DASH_IN_HEADING = /^#{1,6} .* - /;

/**
 * Phrases that are always the wrong register here. The documentation is
 * reference material for a library: it states what an option does and what the
 * default is. A person using the grid is a user, and a person reading the page
 * is you; the rest are closing flourishes and design commentary, which say
 * nothing an instruction needs.
 *
 * Each is a phrase, not a word, so an ordinary use of "worth" or "point" is
 * untouched.
 */
const BANNED_PHRASES = [
  ["the", "reader"],
  ["that", "is", "the", "whole"],
  ["is", "the", "whole", "point"],
  ["which", "is", "the", "point"],
  ["worth", "naming"],
  ["worth", "knowing"],
  // Split into words so this file does not fail itself, the same reason the em
  // dash above is written as an escape.
].map((words) => words.join(" "));

const RULES = [
  {
    what: "an em dash",
    fix: "use a plain dash, a colon or a full stop",
    applies: () => true,
    hit: (line) => line.includes(EM_DASH),
  },
  {
    what: "a phrase from the banned list",
    fix: 'say "the user" or "you", and drop the flourish',
    applies: () => true,
    hit: (line) => {
      const lower = line.toLowerCase();
      return BANNED_PHRASES.some((phrase) => lower.includes(phrase));
    },
  },
  {
    what: "a spaced dash in a docs heading",
    fix: "use a colon; the slug keeps a dash and every link to the heading moves",
    applies: (path) => path.startsWith("src/docs/") && path.endsWith(".md"),
    hit: (line) => DASH_IN_HEADING.test(line),
  },
];

const files = sourceFiles();
if (files.length < 200) {
  console.error(
    `Only ${files.length} files scanned, which means the walk is broken.`,
  );
  process.exit(1);
}

let failed = false;

for (const rule of RULES) {
  const hits = [];

  for (const absolute of files) {
    const path = relative(ROOT, absolute).replaceAll("\\", "/");
    if (!rule.applies(path)) continue;

    for (const [index, line] of readFileSync(absolute, "utf8")
      .split(/\r?\n/)
      .entries()) {
      if (rule.hit(line)) hits.push(`  ${path}:${index + 1}: ${line.trim()}`);
    }
  }

  if (hits.length > 0) {
    failed = true;
    console.error(
      `${hits.length} × ${rule.what} (${rule.fix}):\n${hits.join("\n")}\n`,
    );
  }
}

if (failed) process.exit(1);
console.log(`House style OK (${files.length} files).`);
